    sub = p.add_subparsers(dest="command", required=True)

    sub.add_parser("init")
    sub.add_parser("rebuild")
    gc = sub.add_parser("gc")
    gc.add_argument("--days", type=int, default=14)
    gc.add_argument("--dry-run", action="store_true")
    dream = sub.add_parser("dream")
    dream.add_argument("--tag")
    dream.add_argument("--apply-stdin", action="store_true")
    dream.add_argument("--author")

    add = sub.add_parser("add")
    add_sub = add.add_subparsers(dest="entry_type", required=True)

    dec = add_sub.add_parser("decision")
    dec.add_argument("--title")
    dec.add_argument("--status", choices=["proposed", "accepted", "rejected", "superseded"])
    dec.add_argument("--context")
    dec.add_argument("--decision")
    dec.add_argument("--consequences")
    dec.add_argument("--tags")
    dec.add_argument("--links")
    dec.add_argument("--supersedes")
    dec.add_argument("--consolidates")
    dec.add_argument("--stdin", action="store_true")
    dec.add_argument("--author", help="who logged this: you, claude, codex, copilot, local-model, ...")

    learn = add_sub.add_parser("learning")
    learn.add_argument("--title")
    learn.add_argument("--tried")
    learn.add_argument("--result")
    learn.add_argument("--takeaway")
    learn.add_argument("--tags")
    learn.add_argument("--links")
    learn.add_argument("--consolidates")
    learn.add_argument("--stdin", action="store_true")
    learn.add_argument("--author")

    q = add_sub.add_parser("question")
    q.add_argument("--text")
    q.add_argument("--tags")
    q.add_argument("--links")
    q.add_argument("--stdin", action="store_true")
    q.add_argument("--author")

    note = add_sub.add_parser("note")
    note.add_argument("--title")
    note.add_argument("--body")
    note.add_argument("--tags")
