def cmd_search(args):
    if not DB_PATH.exists():
        sync_all()
    entries = load_entries()
    by_id = {e["id"]: e for e in entries}
    conn = sqlite3.connect(DB_PATH)
    try:
        rows = conn.execute(
            "SELECT id, type, title FROM entries_fts WHERE entries_fts MATCH ? ORDER BY rank",
            (args.query,),
        ).fetchall()
    except sqlite3.OperationalError:
        like = f"%{args.query}%"
        rows = conn.execute(
            "SELECT id, type, title FROM entries WHERE title LIKE ? OR body_json LIKE ?",
            (like, like),
        ).fetchall()
    conn.close()
    if not args.include_inactive:
        rows = [r for r in rows if by_id.get(r[0], {}).get("status") not in INACTIVE_STATUSES]
    if not rows:
        print("No matches.")
    for r in rows:
        print(f"{r[0]}\t{r[1]}\t{r[2]}")


def cmd_list(args):
    entries = load_entries()
    rows = [e for e in entries if e["type"] == args.entry_type]
    if not args.include_inactive:
        rows = [e for e in rows if e.get("status") not in INACTIVE_STATUSES]
    if args.status:
        rows = [e for e in rows if e.get("status") == args.status]
    rows.sort(key=lambda x: x["created_at"], reverse=True)
    if args.limit:
        rows = rows[: args.limit]
    for e in rows:
        print(f"{e['id']}\t{e.get('status')}\t{e['created_at'][:10]}\t{e['title']}")


