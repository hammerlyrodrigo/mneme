_entries_cache = {"mtime": None, "entries": []}


def load_entries_cached():
    """Cache load_entries() across requests in the long-lived `serve` process.

    Keyed on entries.jsonl's mtime so a big log isn't re-parsed on every
    request; invalidated automatically the moment the file changes.
    """
    try:
        mtime = LOG_PATH.stat().st_mtime
    except FileNotFoundError:
        return []
    if _entries_cache["mtime"] != mtime:
        _entries_cache["entries"] = load_entries()
        _entries_cache["mtime"] = mtime
    return _entries_cache["entries"]


def compute_stats(entries):
    """Aggregate counts/facets for the viewer's tabs, filters, and banners.

    Cheap to compute (a single pass) and small to send, so the client never
    needs the full entry set just to render tab counts or filter options --
    that's what keeps the viewer usable once a log has thousands of entries.
    """
    counts = {"all": len(entries)}
    statuses_by_type = {}
    tag_counts = {}
    authors = set()
    for e in entries:
        counts[e["type"]] = counts.get(e["type"], 0) + 1
        if e.get("status"):
            statuses_by_type.setdefault(e["type"], set()).add(e["status"])
        for t in e.get("tags") or []:
            tag_counts[t] = tag_counts.get(t, 0) + 1
        authors.add(e.get("author") or "unspecified")
    pending_reminders = sum(1 for e in entries if e["type"] == "reminder" and e.get("status") == "pending")
    handovers = [e for e in entries if e["type"] == "handover"]
    latest_handover = None
    if handovers:
        h = max(handovers, key=lambda x: x["created_at"])
        latest_handover = {"id": h["id"], "fields": h.get("fields", {})}
    top_tags = sorted(tag_counts.items(), key=lambda kv: (-kv[1], kv[0]))[:50]
    return {
        "counts": counts,
        "statuses_by_type": {k: sorted(v) for k, v in statuses_by_type.items()},
        "tags": [t for t, _ in top_tags],
        "authors": sorted(authors),
        "pending_reminders": pending_reminders,
        "latest_handover": latest_handover,
    }


def annotate_superseded_by(entries, page):
    """Attach `superseded_by` to decisions the caller doesn't otherwise see.

    Computed on read (never stored) by scanning for any decision whose
    `supersedes` points back at it -- so the viewer can render a "superseded
    by" link without holding the whole dataset client-side.
    """
    reverse = {}
    for e in entries:
        if e["type"] == "decision" and e.get("supersedes"):
            reverse[e["supersedes"]] = e["id"]
    out = []
    for e in page:
        if e["id"] in reverse:
            e = dict(e, superseded_by=reverse[e["id"]])
        out.append(e)
    return out


def query_entries(entries, ids=None, q=None, type_filter=None, status_filter=None,
                   tag_filter=None, author_filter=None, since=None, until=None,
                   sort="created_desc", limit=20, offset=0):
    """Filter + sort + paginate, all server-side, for /api/entries.

    `ids` is a batch by-id lookup (used to resolve a cross-link that may not
    be on the caller's current page) and short-circuits every other filter.
    `since`/`until` compare against the date portion only (YYYY-MM-DD), to
    match a plain <input type=date> without timezone-offset ambiguity.
    """
    if ids:
        by_id = {e["id"]: e for e in entries}
        found = [by_id[i] for i in ids if i in by_id]
        return found, len(found)

    rows = entries
    if type_filter and type_filter != "all":
        rows = [e for e in rows if e["type"] == type_filter]
    if status_filter and status_filter != "all":
        rows = [e for e in rows if (e.get("status") or "") == status_filter]
    if tag_filter and tag_filter != "all":
        rows = [e for e in rows if tag_filter in (e.get("tags") or [])]
    if author_filter and author_filter != "all":
        rows = [e for e in rows if (e.get("author") or "unspecified") == author_filter]
    if since:
        rows = [e for e in rows if e["created_at"][:10] >= since]
    if until:
        rows = [e for e in rows if e["created_at"][:10] <= until]

    q = (q or "").strip().lower()
    if q:
        terms = q.split()

        def haystack(e):
            parts = [
                e.get("id", ""), e.get("title", ""), e.get("type", ""),
                e.get("status") or "", e.get("author") or "",
                " ".join(e.get("tags") or []), " ".join(e.get("links") or []),
            ]
            parts.extend(str(v) for v in (e.get("fields") or {}).values())
            return " ".join(parts).lower()

