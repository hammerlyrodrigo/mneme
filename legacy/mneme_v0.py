def cmd_serve(args):
    if not LOG_PATH.exists():
        print(f"No memory log found at {LOG_PATH}. Run 'python scripts/memory.py init' first.", file=sys.stderr)
        sys.exit(1)
    httpd = http.server.ThreadingHTTPServer((args.host, args.port), MemoryViewerHandler)
    url = f"http://{args.host}:{args.port}/"
    print(f"Serving memory viewer for {ROOT.name} at {url} (Ctrl+C to stop)")
    if args.open:
        webbrowser.open(url)
    try:
        httpd.serve_forever()
    except KeyboardInterrupt:
        print("\nStopping.")
    finally:
        httpd.server_close()


def cmd_gc(args):
    """Run deterministic cleanup over stale or dead memory records.

    The command is intentionally rule-based rather than LLM-powered: it archives
    old handovers by branch and flags links that no longer resolve to a file in
    the repository. `--dry-run` prints the actions without changing the log.
    """
    entries = load_entries()
    active_handover = [e for e in entries if e["type"] == "handover" and e.get("status") == "active"]
    current_branches = set()
    try:
        res = subprocess.run(["git", "branch", "--format=%(refname:short)"], cwd=ROOT, capture_output=True, text=True, check=True, timeout=2)
        current_branches = {line.strip() for line in res.stdout.splitlines() if line.strip()}
    except Exception:
        current_branches = set()

    def parse_ts(value):
        try:
            return datetime.fromisoformat(value)
        except Exception:
            return datetime.now(timezone.utc).astimezone()

    cutoff = datetime.now(timezone.utc).astimezone() - timedelta(days=args.days)
    grouped = {}
    for e in active_handover:
        branch = e.get("branch") or "unknown"
        grouped.setdefault(branch, []).append(e)

    archive_targets = []
    stale_targets = []
    for branch, items in grouped.items():
        newest = max(items, key=lambda e: parse_ts(e["created_at"]))
        if branch not in current_branches:
            archive_targets.extend(e["id"] for e in items)
            continue
        for e in items:
            if e["id"] == newest["id"]:
                continue
            if parse_ts(e["created_at"]) < cutoff or branch not in ("main", "master"):
                archive_targets.append(e["id"])

    for e in entries:
        if e.get("status") != "active":
            continue
        for link in e.get("links", []) or []:
            if link.startswith("http"):
                continue
            if re.fullmatch(r"[A-Z](?:\d{4}|-\d{6}-[0-9a-f]{4})", link, re.I):
                continue
            if "/" in link or link.lower().endswith((".md", ".py", ".rs", ".txt", ".json", ".yaml", ".yml", ".toml", ".js", ".ts", ".html", ".css", ".svg", ".png", ".jpg", ".jpeg", ".gif", ".xml", ".ini", ".cfg")):
                if not (ROOT / link).exists():
                    stale_targets.append(e["id"])

    archive_targets = sorted(set(archive_targets))
    stale_targets = sorted(set(stale_targets))
    if args.dry_run:
        print(f"Dry run: would archive {len(archive_targets)} handovers and mark {len(stale_targets)} entries stale.")
        for target in archive_targets:
            print(f"archive {target}")
        for target in stale_targets:
            print(f"stale {target}")
        return

    for target in archive_targets:
        append_patch(target, "gc", status="archived")
    for target in stale_targets:
        append_patch(target, "gc", status="stale")
    sync_all()
    print(f"GC complete: archived {len(archive_targets)}, stale {len(stale_targets)}.")


def cmd_dream(args):
    """Generate or apply a memory consolidation prompt.

    In prompt mode, this collects active learning/note/concept/decision entries
    and emits a structured JSON prompt meant to be piped into an LLM. In apply
    mode, it reads a JSON array of actions and writes consolidate/archive patches
    back into the log.
    """
    if args.apply_stdin:
        actions = json.loads(sys.stdin.read())
        if not isinstance(actions, list):
            raise ValueError("--apply-stdin expects a JSON array of actions")
        for action in actions:
            kind = action.get("action")
            author = args.author or DEFAULT_AUTHOR
            if kind == "consolidate":
                entry_type = action.get("entry_type")
                if entry_type not in {"learning", "note", "concept", "decision"}:
                    raise ValueError(f"Unsupported consolidate type: {entry_type}")
                title = action.get("title") or "Consolidated memory"
                ts = now_iso()
                eid = generate_id(entry_type, author, title, ts)
                entry = {
                    "op": "create",
                    "id": eid,
                    "type": entry_type,
                    "created_at": ts,
                    "updated_at": ts,
                    "title": title,
                    "status": DEFAULT_STATUS.get(entry_type, "active"),
                    "tags": action.get("tags", []),
                    "links": action.get("links", []),
                    "author": author,
                    "branch": current_branch(),
                    "consolidates": action.get("consolidates", []),
                    "fields": action.get("fields", {}),
                }
                append_entry(entry)
                for old_id in action.get("consolidates", []):
                    append_patch(old_id, author, status="consolidated", consolidated_into=eid)
            elif kind == "archive":
                append_patch(action["target_id"], author, status="archived", reason=action.get("reason", ""))
        sync_all()
        print(f"Applied {len(actions)} dream actions.")
        return

    entries = load_entries()
    active = [
        e for e in entries
        if e.get("status") == "active" and e["type"] in {"learning", "note", "concept", "decision"}
    ]
    if args.tag:
        active = [e for e in active if args.tag in e.get("tags", [])]

    clusters = []
    for e in active:
        placed = False
        for cluster in clusters:
            combined_tags = set(cluster["tags"]) | set(e.get("tags", []))
            combined_links = set(cluster["links"]) | set(e.get("links", []))
            if combined_tags != cluster["tags"] or combined_links != cluster["links"]:
                # conservative overlap heuristic
                if set(e.get("tags", [])) & set(cluster["tags"]) or set(e.get("links", [])) & set(cluster["links"]):
                    cluster["entries"].append(e)
                    cluster["tags"].update(e.get("tags", []))
                    cluster["links"].update(e.get("links", []))
                    placed = True
                    break
        if not placed:
            clusters.append({
                "tags": set(e.get("tags", [])),
                "links": set(e.get("links", [])),
                "entries": [e],
            })

    prompt = {
        "task": "Consolidate active memory entries into stronger, clearer entries.",
        "return_format": "A JSON array of actions matching the schema in the refactor spec.",
        "clusters": [
            {
                "tag_set": sorted(cluster["tags"]),
                "link_set": sorted(cluster["links"]),
                "entries": [
                    {"id": e["id"], "type": e["type"], "title": e["title"], "tags": e.get("tags", []), "links": e.get("links", [])}
                    for e in cluster["entries"]
                ],
            }
            for cluster in clusters
        ],
    }
    print("# Dream consolidation prompt")
    print("Return only a JSON array of actions with the shape specified in the memory.py refactor spec.")
    print(json.dumps(prompt, ensure_ascii=False, indent=2))


def build_parser():
    """Create the CLI parser and document the supported commands.

    This function centralizes all subcommands so the script stays discoverable,
    tool-friendly, and easier to extend. It also keeps the `--stdin` contract in
    one place for add commands that can be fed from LLMs or scripts.
    """
