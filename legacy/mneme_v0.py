class MemoryViewerHandler(http.server.BaseHTTPRequestHandler):
    server_version = "MemoryViewer/1.0"

    def _send_json(self, obj, status=200):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def _send_html(self, html):
        body = html.encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        parsed = urllib.parse.urlsplit(self.path)
        qs = urllib.parse.parse_qs(parsed.query)

        def qget(name, default=None):
            v = qs.get(name)
            return v[0] if v else default

        def qint(name, default):
            try:
                return int(qget(name, default))
            except (TypeError, ValueError):
                return default

        try:
            if parsed.path in ("/", "/index.html"):
                self._send_html(VIEWER_HTML)
            elif parsed.path == "/api/meta":
                mtime = LOG_PATH.stat().st_mtime if LOG_PATH.exists() else 0
                self._send_json({"mtime": mtime, "project": ROOT.name})
            elif parsed.path == "/api/stats":
                entries = load_entries_cached()
                mtime = LOG_PATH.stat().st_mtime if LOG_PATH.exists() else 0
                self._send_json({**compute_stats(entries), "mtime": mtime, "project": ROOT.name})
            elif parsed.path == "/api/entries":
                entries = load_entries_cached()
                ids_param = qget("ids")
                ids = [i for i in ids_param.split(",") if i] if ids_param else None
                page, total = query_entries(
                    entries, ids=ids, q=qget("q"), type_filter=qget("type"),
                    status_filter=qget("status"), tag_filter=qget("tag"),
                    author_filter=qget("author"), since=qget("since"), until=qget("until"),
                    sort=qget("sort", "created_desc"), limit=qint("limit", 20), offset=qint("offset", 0),
                )
                page = annotate_superseded_by(entries, page)
                self._send_json({"entries": page, "total": total})
            else:
                self._send_json({"error": "not found"}, status=404)
        except Exception as exc:
            self._send_json({"error": str(exc)}, status=500)

    def log_message(self, fmt, *fmt_args):
        sys.stderr.write("[memory serve] " + (fmt % fmt_args) + "\n")


