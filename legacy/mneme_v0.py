#!/usr/bin/env python3
"""Project memory harness for Demiurge.

This script is the single write path for the repository's working memory. It
stores append-only JSON events in `.memory/log/entries.jsonl`, rebuilds the
SQLite index and generated markdown summaries, and exposes a small CLI for
recording decisions, goals, questions, learnings, reminders, and session
handover checkpoints.

Design intent
-------------
The log is intentionally append-only: new facts are added as events, not by
rewriting the whole journal in place. Generated markdown files under
`.memory/` are derived from the log and should be treated as artifacts rather
than source-of-truth files. The one exception is `.memory/goals.md`, which is
curated by hand like files in `design/`.

Typical workflow
----------------
    python scripts/memory.py init
    python scripts/memory.py add decision --title "Use a simple rule" --context "..." --decision "..." --consequences "..."
    python scripts/memory.py add learning --title "Try logging decisions" --tried "..." --result "..." --takeaway "..."
    python scripts/memory.py resolve Q0001 --answer "We chose ..." --decision D0001
    python scripts/memory.py done R0001 --note "Completed during the session"
    python scripts/memory.py handover --summary "..." --done "..." --next "..." --blockers "..."
    python scripts/memory.py search "slope"
    python scripts/memory.py list decision --limit 20
    python scripts/memory.py serve --open

The script accepts `--author` on write commands; if omitted it falls back to
`MEMORY_AUTHOR`, then the literal string `"unspecified"`.

Entry types map onto a five-part memory model:
    procedural  -> Skills (.claude/skills/, AGENTS.md) -- not stored here
    working     -> the live session; handover.md is a checkpoint of it, not
                   the thing itself
    episodic    -> entries.jsonl itself: decisions/learnings/handovers are
                   dated events
    semantic    -> `concept` entries -> .memory/concepts.md (glossary)
    prospective -> `reminder` entries -> .memory/reminders.md (deferred,
                   already-decided actions; distinct from open questions)

Developer notes
---------------
- `.memory/log/entries.jsonl` is the source of truth.
- Generated Markdown and SQLite files are disposable rebuild artifacts.
- The CLI intentionally supports both direct arguments and `--stdin` for
  agent/LLM integrations that emit structured JSON payloads.
- Branch-aware IDs and status patches are used to preserve lineage across
  parallel work without forcing destructive rewrites of the source log.
"""
