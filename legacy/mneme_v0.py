    note.add_argument("--consolidates")
    note.add_argument("--stdin", action="store_true")
    note.add_argument("--author")

    concept = add_sub.add_parser("concept")
    concept.add_argument("--term")
    concept.add_argument("--definition")
    concept.add_argument("--notes")
    concept.add_argument("--tags")
    concept.add_argument("--links")
    concept.add_argument("--supersedes")
    concept.add_argument("--consolidates")
