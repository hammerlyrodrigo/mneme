    reminder.add_argument("--trigger", help="the future condition/milestone to watch for")
    reminder.add_argument("--action", help="what to do when the trigger occurs")
    reminder.add_argument("--tags")
    reminder.add_argument("--links")
    reminder.add_argument("--stdin", action="store_true")
    reminder.add_argument("--author")

    res = sub.add_parser("resolve")
    res.add_argument("id")
    res.add_argument("--answer", required=True)
    res.add_argument("--decision")
    res.add_argument("--author")

    done = sub.add_parser("done")
    done.add_argument("id")
