def ensure_project_memory_instructions():
    """Ensure the repo-level AGENTS.md contains the current project memory guidance.

    The project has a custom mnemonic for memory handling: `.memory/` is tracked
    as a derived artifact store, generated files must not be hand-edited, and the
    worker must read the handover and goals before continuing. The guidance
    is managed as a bounded block so wording updates can replace prior versions
    without duplicating content.
    """
    ag = ROOT / "AGENTS.md"
    if not ag.exists():
        return

    text = ag.read_text(encoding="utf-8")
    start_marker = "<!-- memory-guidance:auto-managed:start -->"
    end_marker = "<!-- memory-guidance:auto-managed:end -->"
    legacy_marker = "<!-- memory-guidance:auto-managed -->"
    required_phrases = [
        "Never hand-edit a file under `.memory/`",
        "python scripts/memory.py",
        "Read [.memory/handover.md]",
        "Log a `decision`",
    ]
    section = f"""
{start_marker}
## Memory handling for this repo

This project keeps design history, experiments, and session context under `.memory/`.
The memory log is read as the source of truth for the project state, and generated
files in `.memory/` are rebuilt from `.memory/log/entries.jsonl` using `python scripts/memory.py`.

- Never hand-edit a generated file under `.memory/`; it will be overwritten on the next `memory.py` write.
- Read [.memory/handover.md](.memory/handover.md) and [.memory/goals.md](.memory/goals.md) at the start of a session.
- Log a `decision` when a non-obvious choice is settled, a `learning` when a tried approach is abandoned or validated, a `question` when something is intentionally left open, a `concept` when a term definition changes, and a `reminder` when a decision is deferred.
- Run `python scripts/memory.py handover` before ending a session or a natural stopping point.
- Pass `--author` with the active agent name (`claude`, `codex`, `copilot`, `local-model`, or the human) whenever a write is performed so provenance is preserved.
- Keep memory entries tied back to the design work in `design/` and the current simulation-core goals; prefer short, inspectable records over long prose.
{end_marker}
"""
    if start_marker in text and end_marker in text:
        start = text.index(start_marker)
        end = text.index(end_marker, start) + len(end_marker)
        updated = text[:start].rstrip() + "\n\n" + section + "\n"
        ag.write_text(updated, encoding="utf-8")
        return

    if legacy_marker in text:
        start = text.index(legacy_marker)
        updated = text[:start].rstrip() + "\n\n" + section + "\n"
        ag.write_text(updated, encoding="utf-8")
        return

    if all(phrase in text for phrase in required_phrases):
        return
    ag.write_text(text.rstrip() + "\n\n" + section + "\n", encoding="utf-8")


def _normalize_stdin_args(args):
    if not getattr(args, "stdin", False):
        return
    payload = json.loads(sys.stdin.read())
    if not isinstance(payload, dict):
        raise ValueError("--stdin expects a JSON object keyed by CLI argument names")
    for key, value in payload.items():
        if hasattr(args, key):
            current = getattr(args, key)
            if current in (None, "", False) or key in {"tags", "links"} and not current:
                setattr(args, key, value)


def _validate_add_args(args):
    if getattr(args, "stdin", False):
        return
    required = {
        "decision": ["title"],
        "learning": ["title"],
        "question": ["text"],
        "note": ["title"],
        "concept": ["term", "definition"],
        "reminder": ["trigger", "action"],
    }
    missing = [k for k in required.get(args.entry_type, []) if getattr(args, k, None) in (None, "")]
    if missing:
        raise SystemExit(f"Missing required values for {args.entry_type}: {', '.join(missing)}")


def cmd_init(args):
    """Initialize the repository memory workspace and generated artifacts.

    This ensures the `.memory` directory exists, sets up ignore/merge rules, and
    installs lightweight git hooks so the SQLite index and markdown views rebuild
    automatically after Git branch/worktree operations. It also ensures the repo
    keeps the project-specific memory instructions in AGENTS.md without
    duplicating them when the file is already configured.
    """
    MEMORY_DIR.joinpath("log").mkdir(parents=True, exist_ok=True)
    DECISIONS_DIR.mkdir(parents=True, exist_ok=True)
    LOG_PATH.touch(exist_ok=True)
    ensure_project_memory_instructions()

    gitignore_path = MEMORY_DIR / ".gitignore"
    desired_gitignore = """# Disposable SQLite index and generated Markdown views
index.db
index.db.tmp.*
handover.md
open-questions.md
learnings.md
concepts.md
reminders.md
decisions/
"""
    if gitignore_path.exists():
        existing = gitignore_path.read_text(encoding="utf-8")
        lines = set(existing.splitlines())
        for line in desired_gitignore.splitlines():
            if line and line not in lines:
                existing = (existing.rstrip() + "\n" + line + "\n") if existing.strip() else line + "\n"
                lines.add(line)
        gitignore_path.write_text(existing, encoding="utf-8")
    else:
        gitignore_path.write_text(desired_gitignore, encoding="utf-8")

    gitattributes = ROOT / ".gitattributes"
    gitattributes_line = ".memory/log/entries.jsonl merge=union"
    if gitattributes.exists():
        text = gitattributes.read_text(encoding="utf-8")
        if gitattributes_line not in text.splitlines():
            gitattributes.write_text(text.rstrip() + "\n" + gitattributes_line + "\n", encoding="utf-8")
    else:
        gitattributes.write_text(gitattributes_line + "\n", encoding="utf-8")

    hooks_dir = ROOT / ".git" / "hooks"
    if hooks_dir.exists():
        for name in ("post-checkout", "post-merge"):
            hook_path = hooks_dir / name
            if not hook_path.exists():
                hook_path.write_text("#!/bin/sh\npython3 scripts/memory.py rebuild >/dev/null 2>&1 || true\n", encoding="utf-8")
                hook_path.chmod(0o755)
            else:
                content = hook_path.read_text(encoding="utf-8")
                if "scripts/memory.py rebuild" not in content:
                    with hook_path.open("a", encoding="utf-8") as fh:
                        fh.write("\npython3 scripts/memory.py rebuild >/dev/null 2>&1 || true\n")
                    hook_path.chmod(0o755)

    entries, fts_ok = sync_all()
    print(f"Initialized. {len(entries)} entries indexed. FTS5 available: {fts_ok}")


def cmd_add(args):
    """Create a new memory entry from parsed CLI arguments or JSON stdin.

    `--stdin` is especially helpful for agents or LLMs that want to produce a
    properly structured memory event without manually composing shell arguments.
    The function also handles auto-status defaults and records supersede/
    consolidate lineage metadata when requested.
    """
    _normalize_stdin_args(args)
    _validate_add_args(args)
    entries = load_entries()
    ts = now_iso()
    eid = generate_id(args.entry_type, args.author or DEFAULT_AUTHOR, getattr(args, "title", "") or getattr(args, "text", "") or getattr(args, "term", "") or getattr(args, "action", ""), ts)
    if args.entry_type == "question":
        title = args.text
    elif args.entry_type == "concept":
        title = args.term
    elif args.entry_type == "reminder":
        title = args.action
    else:
        title = args.title
    entry = {
        "op": "create",
        "id": eid,
        "type": args.entry_type,
        "created_at": ts,
        "updated_at": ts,
        "title": title,
        "status": None,
        "tags": parse_csv(getattr(args, "tags", None)),
        "links": parse_csv(getattr(args, "links", None)),
        "author": args.author or DEFAULT_AUTHOR,
        "branch": current_branch(),
        "consolidates": [],
        "supersedes": None,
        "fields": {},
    }
    if args.entry_type == "decision":
        entry["status"] = args.status or "accepted"
        entry["supersedes"] = args.supersedes
        entry["consolidates"] = parse_csv(getattr(args, "consolidates", None))
        entry["fields"] = {
            "context": args.context or "",
            "decision": args.decision or "",
            "consequences": args.consequences or "",
        }
    elif args.entry_type == "learning":
        entry["status"] = DEFAULT_STATUS["learning"]
        entry["consolidates"] = parse_csv(getattr(args, "consolidates", None))
        entry["fields"] = {
            "tried": args.tried or "",
            "result": args.result or "",
            "takeaway": args.takeaway or "",
        }
    elif args.entry_type == "question":
        entry["status"] = "open"
        entry["fields"] = {"question": args.text}
    elif args.entry_type == "note":
        entry["status"] = DEFAULT_STATUS["note"]
        entry["consolidates"] = parse_csv(getattr(args, "consolidates", None))
        entry["fields"] = {"body": args.body or ""}
    elif args.entry_type == "concept":
        entry["status"] = DEFAULT_STATUS["concept"]
        entry["supersedes"] = args.supersedes
        entry["consolidates"] = parse_csv(getattr(args, "consolidates", None))
        entry["fields"] = {
            "term": args.term,
            "definition": args.definition or "",
            "notes": args.notes or "",
        }
    elif args.entry_type == "reminder":
        entry["status"] = "pending"
        entry["fields"] = {"trigger": args.trigger or "", "action": args.action}

    append_entry(entry)
    if getattr(args, "supersedes", None):
        if args.entry_type in {"decision", "concept"}:
            append_patch(args.supersedes, args.author or DEFAULT_AUTHOR, status="superseded", superseded_by=eid)
    if getattr(args, "consolidates", None):
        if args.entry_type in {"learning", "note", "concept", "decision"}:
            for old_id in parse_csv(args.consolidates):
                append_patch(old_id, args.author or DEFAULT_AUTHOR, status="consolidated", consolidated_into=eid)
    sync_all()
    print(f"Added {eid}: {entry['title']}")


