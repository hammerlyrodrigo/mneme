PREFIX = {
    "decision": "D",
    "learning": "L",
    "question": "Q",
    "note": "N",
    "handover": "H",
    "concept": "C",
    "reminder": "R",
}

DEFAULT_AUTHOR = os.environ.get("MEMORY_AUTHOR", "unspecified")
INACTIVE_STATUSES = {"superseded", "consolidated", "archived", "rejected", "obsolete", "stale"}
DEFAULT_STATUS = {
    "decision": "accepted",
    "question": "open",
    "reminder": "pending",
    "learning": "active",
    "note": "active",
    "concept": "active",
    "handover": "active",
}


def now_iso():
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def current_branch():
    """Return the active git branch name for branch-aware memory records.

    This is used when a memory event is created or patched so that handovers and
    follow-up work can stay traceable to the branch that authored the change.
    When detached HEAD is detected, we fall back to a human-readable label.
    """
    try:
        res = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
            timeout=2,
        )
        return res.stdout.strip() or "detached"
    except Exception:
        return "unknown"


def generate_id(entry_type, author, title, ts):
    """Create a deterministic, branch-safe ID with a short hash suffix.

    The format is intentionally compact and readable for the generated view and
    cross-links in the browser. It is not monotonic like the old numeric IDs, but
    it remains stable for the same input and avoids collisions across branches.
    """
    prefix = PREFIX[entry_type]
    date_part = ts[2:10].replace("-", "")
    seed = f"{entry_type}:{author}:{title}:{ts}:{os.urandom(4).hex()}"
    digest = hashlib.sha256(seed.encode("utf-8")).hexdigest()[:4]
    return f"{prefix}-{date_part}-{digest}"


def load_entries():
    """Fold the append-only JSON log back into final in-memory entries.

    Each line is either a create event or a patch event. We replay patch events
    in order so `by_id` reflects the latest state of each entry without rewriting
    the log itself.
    """
    if not LOG_PATH.exists():
        return []
    by_id = {}
    with LOG_PATH.open("r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            entry = json.loads(line)
            op = entry.get("op", "create")
            if op == "create":
                rec = dict(entry)
                rec.setdefault("op", "create")
                rec.setdefault("branch", current_branch())
                rec.setdefault("status", DEFAULT_STATUS.get(rec.get("type"), "active"))
                rec.setdefault("tags", [])
                rec.setdefault("links", [])
                rec.setdefault("fields", {})
                rec.setdefault("consolidates", [])
                by_id[rec["id"]] = rec
            elif op == "patch":
                target_id = entry.get("target_id")
                target = by_id.get(target_id)
                if target is None:
                    continue
                target["updated_at"] = entry["updated_at"]
                patch = entry.get("patch") or {}
                for key, value in patch.items():
                    if key == "fields":
                        target.setdefault("fields", {})
                        if isinstance(value, dict):
                            target["fields"].update(value)
                        continue
                    target[key] = value
                target.setdefault("branch", entry.get("branch", current_branch()))
    return list(by_id.values())


def next_id(entries, entry_type):
    return generate_id(entry_type, DEFAULT_AUTHOR, "auto", now_iso())


def append_entry(entry):
    MEMORY_DIR.joinpath("log").mkdir(parents=True, exist_ok=True)
    with LOG_PATH.open("a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")


def append_patch(target_id, author, **patch_fields):
    """Append a mutation event for an existing entry.

    This is the preferred way to update status or metadata. It keeps the log
    append-only and ensures later `load_entries()` folds the incremental change
    into the final object without editing the original record in place.
    """
    payload = {
        "op": "patch",
        "target_id": target_id,
        "updated_at": now_iso(),
        "author": author or DEFAULT_AUTHOR,
        "branch": current_branch(),
        "patch": patch_fields,
    }
    append_entry(payload)


def parse_csv(value):
    if not value:
        return []
    return [v.strip() for v in value.split(",") if v.strip()]


# ---------------------------------------------------------------- SQLite index

def rebuild_db(entries):
    """Rebuild the disposable SQLite index atomically.

    We write the index to a temporary file in the same directory and replace the
    live DB only after the commit succeeds. This keeps search queries from ever
    seeing a partially-written database in the middle of a rebuild.
    """
    tmp_db = MEMORY_DIR / f"index.db.tmp.{os.getpid()}"
    if tmp_db.exists():
        tmp_db.unlink()
    conn = sqlite3.connect(tmp_db)
    conn.execute(
        "CREATE TABLE entries (id TEXT PRIMARY KEY, type TEXT, status TEXT, branch TEXT, "
        "created_at TEXT, updated_at TEXT, title TEXT, tags TEXT, links TEXT, "
        "author TEXT, body_json TEXT)"
    )
    fts_ok = True
    try:
        conn.execute(
            "CREATE VIRTUAL TABLE entries_fts USING fts5("
            "id UNINDEXED, type UNINDEXED, title, body, tags)"
        )
    except sqlite3.OperationalError:
        fts_ok = False

    for e in entries:
        searchable_body = " ".join(str(v) for v in e.get("fields", {}).values())
        conn.execute(
            "INSERT INTO entries VALUES (?,?,?,?,?,?,?,?,?,?,?)",
            (
                e["id"], e["type"], e.get("status"), e.get("branch"), e["created_at"], e["updated_at"],
                e["title"], ",".join(e.get("tags", [])), ",".join(e.get("links", [])),
                e.get("author", DEFAULT_AUTHOR), json.dumps(e.get("fields", {})),
            ),
        )
        if fts_ok:
            conn.execute(
                "INSERT INTO entries_fts VALUES (?,?,?,?,?)",
                (e["id"], e["type"], e["title"], searchable_body, ",".join(e.get("tags", []))),
            )
    conn.commit()
    conn.close()
    os.replace(tmp_db, DB_PATH)
    return fts_ok


# ---------------------------------------------------------------- Markdown views

def slugify(title):
    slug = "-".join(title.lower().split())[:40]
    slug = "".join(c for c in slug if c.isalnum() or c == "-")
    slug = re.sub(r"-{2,}", "-", slug).strip("-")
    return slug


def render_decision(e):
    f = e["fields"]
    lines = [GENERATED_HEADER, f"# {e['id']}: {e['title']}\n"]
    lines.append(f"- Status: {e.get('status')}")
    lines.append(f"- Date: {e['created_at']}")
    if e.get("tags"):
        lines.append(f"- Tags: {', '.join(e['tags'])}")
    if e.get("links"):
        lines.append(f"- Links: {', '.join(e['links'])}")
    if e.get("supersedes"):
        lines.append(f"- Supersedes: {e['supersedes']}")
    lines.append("")
    lines.append("## Context\n")
    lines.append(f.get("context", "") + "\n")
    lines.append("## Decision\n")
    lines.append(f.get("decision", "") + "\n")
    lines.append("## Consequences\n")
    lines.append(f.get("consequences", "") + "\n")
    return "\n".join(lines)


def render_concepts(entries):
    """Render the active concept glossary from the current memory state.

    This intentionally excludes superseded, archived, and other inactive concept
    entries so the glossary reflects only the accepted current definition of each
    term.
    """
    concepts = [e for e in entries if e["type"] == "concept" and e.get("status") == "active"]
    latest = {}
    for e in sorted(concepts, key=lambda x: x["created_at"]):
        latest[e["fields"]["term"]] = e
    lines = [GENERATED_HEADER, "# Concepts (semantic memory)\n"]
    lines.append(
        "Definitions of terms as we currently understand them for the "
        "simulation core. Revisions replace the shown definition but keep "
        "prior versions in `.memory/log/entries.jsonl`. For the fuller design "
        "rationale behind a term, follow its links into `design/`.\n"
    )
    for term in sorted(latest, key=str.lower):
        e = latest[term]
        f = e["fields"]
        lines.append(f"## {term} ({e['id']})\n")
        lines.append(f.get("definition", "") + "\n")
        if f.get("notes"):
            lines.append(f"_Notes: {f['notes']}_\n")
        if e.get("links"):
            lines.append(f"Links: {', '.join(e['links'])}\n")
    if not latest:
        lines.append("_No concepts logged yet._")
    CONCEPTS_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


def render_reminders(entries):
    reminders = [e for e in entries if e["type"] == "reminder"]
    pending = [e for e in reminders if e.get("status") == "pending"]
    done = [e for e in reminders if e.get("status") == "done"]
    lines = [GENERATED_HEADER, "# Reminders (prospective memory)\n"]
    lines.append(
        "Things already decided but deliberately deferred to a future "
        "trigger, distinct from `open-questions.md` (undecided now).\n"
    )
    lines.append("## Pending\n")
    for e in sorted(pending, key=lambda x: x["created_at"], reverse=True):
        f = e["fields"]
        lines.append(f"- **{e['id']}** when {f.get('trigger', '')}: {f.get('action', '')}")
    if not pending:
        lines.append("_None pending._")
    lines.append("\n## Done\n")
    for e in sorted(done, key=lambda x: x["updated_at"], reverse=True)[:20]:
        f = e["fields"]
        lines.append(f"- **{e['id']}** when {f.get('trigger', '')}: {f.get('action', '')} -- {f.get('note', '')}")
    REMINDERS_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return pending


def render_all_markdown(entries):
    """Regenerate all derived markdown artifacts from the current entry set.

    This includes per-decision files, decision index, open questions, learnings,
    concepts, reminders, and the branch-aware handover summary. These files are
    generated from the underlying log and should remain reproducible.
    """
    DECISIONS_DIR.mkdir(parents=True, exist_ok=True)

    decisions = [e for e in entries if e["type"] == "decision"]
    old_files = set(DECISIONS_DIR.glob("d*.md"))
    keep_files = set()
    for e in decisions:
        slug = slugify(e["title"])
        path = DECISIONS_DIR / f"{e['id'].lower()}-{slug}.md"
        path.write_text(render_decision(e), encoding="utf-8")
        keep_files.add(path)
    for stale in old_files - keep_files:
        stale.unlink()

    index_lines = [GENERATED_HEADER, "# Decision index\n"]
    for e in sorted(decisions, key=lambda x: x["id"]):
        slug = slugify(e["title"])
        fname = f"{e['id'].lower()}-{slug}.md"
        index_lines.append(f"- [{e['id']}: {e['title']}]({fname}) -- {e.get('status')}")
    if not decisions:
        index_lines.append("_No decisions logged yet._")
    DECISIONS_INDEX_MD.write_text("\n".join(index_lines) + "\n", encoding="utf-8")

    questions = [e for e in entries if e["type"] == "question"]
    open_q = [e for e in questions if e.get("status") == "open"]
    resolved_q = [e for e in questions if e.get("status") == "resolved"]
    q_lines = [GENERATED_HEADER, "# Open questions\n"]
    for e in sorted(open_q, key=lambda x: x["created_at"], reverse=True):
        tags = f" ({', '.join(e['tags'])})" if e.get("tags") else ""
        q_lines.append(f"- **{e['id']}** [{e['created_at'][:10]}]{tags}: {e['fields']['question']}")
        if e.get("links"):
            q_lines.append(f"  - links: {', '.join(e['links'])}")
    if not open_q:
        q_lines.append("_No open questions._")
    q_lines.append("\n## Resolved\n")
    for e in sorted(resolved_q, key=lambda x: x["updated_at"], reverse=True)[:20]:
        ans = e["fields"].get("answer", "")
        dec = f" (see {e['fields']['resolved_by']})" if e["fields"].get("resolved_by") else ""
        q_lines.append(f"- **{e['id']}**: {e['fields']['question']} -> {ans}{dec}")
    QUESTIONS_MD.write_text("\n".join(q_lines) + "\n", encoding="utf-8")

    learnings = [e for e in entries if e["type"] == "learning" and e.get("status") == "active"]
    l_lines = [GENERATED_HEADER, "# Learnings (things we tried)\n"]
    for e in sorted(learnings, key=lambda x: x["created_at"], reverse=True):
        f = e["fields"]
        tags = f" ({', '.join(e['tags'])})" if e.get("tags") else ""
        l_lines.append(f"## {e['id']}: {e['title']}{tags}\n")
        l_lines.append(f"- Tried: {f.get('tried', '')}")
        l_lines.append(f"- Result: {f.get('result', '')}")
        l_lines.append(f"- Takeaway: {f.get('takeaway', '')}\n")
    if not learnings:
        l_lines.append("_No learnings logged yet._")
    LEARNINGS_MD.write_text("\n".join(l_lines) + "\n", encoding="utf-8")

    render_concepts(entries)
    pending_reminders = render_reminders(entries)

    handovers = sorted(
        [e for e in entries if e["type"] == "handover" and e.get("status") == "active"], key=lambda x: x["created_at"]
    )
    branch = current_branch()
    current_handover = next(
        (e for e in reversed(handovers) if e.get("branch") == branch),
        None,
    )
    mainline_handover = next(
        (e for e in reversed(handovers) if e.get("branch") in ("main", "master")),
        None,
    )
    h_lines = [GENERATED_HEADER, "# Handover\n"]
    if current_handover:
        f = current_handover["fields"]
        h_lines.append(f"_Last updated: {current_handover['created_at']} | {len(handovers)} active session(s) logged_\n")
        h_lines.append(f"## Current Branch Focus ({branch})\n")
        h_lines.append(f.get("summary", "") + "\n")
        h_lines.append("## Done this session\n")
        h_lines.append(f.get("done", "") + "\n")
        h_lines.append("## Next\n")
        h_lines.append(f.get("next", "") + "\n")
        h_lines.append("## Blockers\n")
        h_lines.append((f.get("blockers") or "None") + "\n")
        if branch not in ("main", "master") and mainline_handover and mainline_handover.get("id") != current_handover.get("id"):
            mf = mainline_handover["fields"]
            h_lines.append("## Latest Mainline Checkpoint\n")
            h_lines.append(f"- {mainline_handover['id']} [{mainline_handover.get('branch', 'main')}] :: {mf.get('summary', '')}\n")
    elif handovers:
        last = handovers[-1]
        f = last["fields"]
        h_lines.append(f"_Last updated: {last['created_at']} | {len(handovers)} session(s) logged_\n")
        h_lines.append("## Current focus\n")
        h_lines.append(f.get("summary", "") + "\n")
        h_lines.append("## Done this session\n")
        h_lines.append(f.get("done", "") + "\n")
        h_lines.append("## Next\n")
        h_lines.append(f.get("next", "") + "\n")
        h_lines.append("## Blockers\n")
        h_lines.append((f.get("blockers") or "None") + "\n")
    else:
        h_lines.append("_No handover recorded yet. Run `memory.py handover` at the end of a session._\n")

    if open_q:
        h_lines.append("## Open questions (top 5)\n")
        for e in sorted(open_q, key=lambda x: x["created_at"], reverse=True)[:5]:
            h_lines.append(f"- {e['id']}: {e['fields']['question']}")
        h_lines.append("")
    if decisions:
        h_lines.append("## Recent decisions (last 5)\n")
        for e in sorted(decisions, key=lambda x: x["created_at"], reverse=True)[:5]:
            h_lines.append(f"- {e['id']}: {e['title']} [{e.get('status')}]")
        h_lines.append("")
    if pending_reminders:
        h_lines.append("## Reminders due for attention\n")
        for e in sorted(pending_reminders, key=lambda x: x["created_at"], reverse=True):
            f = e["fields"]
            h_lines.append(f"- {e['id']} when {f.get('trigger', '')}: {f.get('action', '')}")
        h_lines.append("")
    h_lines.append("---\nFull history: `.memory/log/entries.jsonl`. Older handovers are type `handover` there.\n")
    HANDOVER_MD.write_text("\n".join(h_lines), encoding="utf-8")


def sync_all():
    """Rebuild derived artifacts from the current JSON log.

    This is the central lifecycle hook that keeps the SQLite index and generated
    markdown files synchronized after any add, patch, or maintenance command.
    """
    entries = load_entries()
    fts_ok = rebuild_db(entries)
    render_all_markdown(entries)
    return entries, fts_ok


