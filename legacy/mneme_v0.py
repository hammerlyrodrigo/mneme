def main():
    """Dispatch the requested CLI command to its handler.

    The script intentionally keeps command registration in a single mapping so
    new commands can be added without scattering dispatch logic across the file.
    """
    parser = build_parser()
    args = parser.parse_args()
    {
        "init": cmd_init,
        "add": cmd_add,
        "resolve": cmd_resolve,
        "done": cmd_done,
        "handover": cmd_handover,
        "search": cmd_search,
        "list": cmd_list,
        "show": cmd_show,
        "rebuild": cmd_rebuild,
        "gc": cmd_gc,
        "dream": cmd_dream,
        "serve": cmd_serve,
    }[args.command](args)


if __name__ == "__main__":
    main()
